export const DICTIONARIES: Record<Lang, Record<I18nKey, string>> = { en, es };

let currentLang: Lang = 'en';
const listeners = new Set<() => void>();

const applyDocumentLang = (lang: Lang) => {
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
};

export const getLang = (): Lang => currentLang;

export const setLang = (lang: Lang): void => {
  applyDocumentLang(lang);
  if (lang === currentLang) return;
  currentLang = lang;
  for (const fn of listeners) fn();
};

export const subscribeLang = (fn: () => void): (() => void) => {
  listeners.add(fn);
  return () => {
    listeners.delete(fn);
  };
};

/** Locale para Intl / toLocale*: fechas y números en el idioma de la UI. */
export const locale = (): string => (currentLang === 'es' ? 'es-MX' : 'en-US');

/** Texto traducido; `{nombre}` se sustituye con `params.nombre`. */
export const t = (key: I18nKey, params?: Record<string, string | number>): string => {
  const text = DICTIONARIES[currentLang][key] ?? en[key] ?? key;
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (m, name: string) =>
    name in params ? String(params[name]) : m
  );
};

/** Plural simple: `one` si count === 1, si no `other`; `{count}` disponible. */
export const tn = (
  count: number,
  one: I18nKey,
  other: I18nKey,
  params?: Record<string, string | number>
): string => t(count === 1 ? one : other, { count, ...params });

/** Hook: re-renderiza el componente al cambiar el idioma. */
export const useLang = (): Lang => useSyncExternalStore(subscribeLang, getLang, getLang);

const isTauri = () => typeof window !== 'undefined' && '__TAURI_INTERNALS__' in window;

const asLang = (code: unknown): Lang => (code === 'es' ? 'es' : 'en');

/** Arranque: idioma resuelto por el backend (preferencia + SO) y escucha de
 *  cambios hechos en otra ventana. Fuera de Tauri (tests) queda en inglés. */
export const initLang = async (): Promise<void> => {
  applyDocumentLang(currentLang);
  if (!isTauri()) return;
  try {
    const { invoke } = await import('@tauri-apps/api/core');
    setLang(asLang(await invoke<string>('ui_language')));
    const { listen } = await import('@tauri-apps/api/event');
    await listen<string>('ui-language-changed', (e) => setLang(asLang(e.payload)));
  } catch (err) {
    console.error('No se pudo leer el idioma de la interfaz:', err);
  }
};

export const getUiLanguagePref = async (): Promise<UiLanguagePref> => {
  if (!isTauri()) return 'auto';
  const { invoke } = await import('@tauri-apps/api/core');
  const pref = await invoke<string>('get_ui_language_pref');
  return pref === 'en' || pref === 'es' ? pref : 'auto';
};

/** Guarda la preferencia; el backend avisa a todas las ventanas. */
export const setUiLanguagePref = async (pref: UiLanguagePref): Promise<void> => {
  if (!isTauri()) {
    setLang(pref === 'es' ? 'es' : 'en');
    return;
  }
  const { invoke } = await import('@tauri-apps/api/core');
  setLang(asLang(await invoke<string>('set_ui_language', { value: pref })));
};
